-- Initial schema, matching the JPA entities in com.daxtonl.mediatracker.model.

create table tracker (
    id   bigint generated by default as identity primary key,
    name varchar(255) not null,
    constraint uk_tracker_name unique (name)
);

create table media (
    id         bigint generated by default as identity primary key,
    tracker_id bigint       not null references tracker (id) on delete cascade,
    name       varchar(255) not null,
    type       varchar(255) not null,
    status     varchar(255) not null,
    length     integer,
    priority   integer,
    rating     integer,
    constraint uk_media_tracker_name unique (tracker_id, name),
    constraint ck_media_type check (type in ('MOVIE', 'GAME', 'SHOW', 'MANGA', 'BOOK')),
    constraint ck_media_status check (status in ('WAITLIST', 'VIEWING', 'FINISHED', 'DROPPED', 'HOLD'))
);

create table view_log (
    id            bigint generated by default as identity primary key,
    media_id      bigint  not null references media (id) on delete cascade,
    viewed_on     date    not null,
    view_progress integer not null
);

create index idx_view_log_media_id on view_log (media_id);
